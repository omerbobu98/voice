// Helper function to get translation
export function t(key, language = 'en') {
  const keys = key.split('.')
  let value = translations
  
  for (const k of keys) {
    if (value && typeof value === 'object' && k in value) {
      value = value[k]
    } else {
      console.warn(`Translation missing: ${key}`)
      return key
    }
  }
  
  if (value && typeof value === 'object' && language in value) {
    return value[language]
  }
  
  console.warn(`Translation missing for language ${language}: ${key}`)
  return key
}

// Hook-compatible translation function creator
export function createTranslator(language) {
  return (key) => t(key, language)
}

export default translations
